import {
  isRegister,
  LIMITS,
  REGISTER_DESCRIPTIONS,
} from '../../../../packages/shared/src/index.ts';
// The collect_writing prompt. The calling agent does the finding and reading
// with its own tools; Tones only receives what the user approves.
export function collectWritingPrompt(where?: string, category?: string) {
  const categories = Object.entries(REGISTER_DESCRIPTIONS)
    .map(([name, description]) => `- ${name}: ${description}`)
    .join('\n');
  const scope = where?.trim()
    ? `Look only here: ${where.trim()}`
    : 'Look in every source you can reach: connected tools such as Slack, email, Google Drive, Notion, Confluence, GitHub, and local files if you have file access. Tell me which sources you are checking before you start.';
  const fixed =
    category && isRegister(category)
      ? `Use the category ${category} for everything unless I change it during review.`
      : 'Choose a category for each candidate.';
  return `Help me teach Tones my writing style. Find writing I authored, show it to me for review, and add only what I approve to Tones.

## 1. Find candidates
${scope}

Collect only text I wrote myself:
- Messages: only messages I sent. Drop quoted replies, forwarded text, and signatures.
- Documents and pages: ones I created or wrote most of. In shared documents, keep only my sections.
- Code hosts: my PR descriptions, issue comments, READMEs, and docs I authored. Not code.
- Local files: prose such as .md, .txt, .html, .docx, and .pdf. Extract the text with the tools you have.

Skip text written by other people or generated by tools or AI, templates, boilerplate, and anything containing secrets or credentials. Flag candidates that include other people's personal details instead of silently including them.

## 2. Shape samples
Each sample must be ${LIMITS.sampleMinChars} to ${LIMITS.sampleMaxChars} characters of my text. Combine short pieces from the same source and category into one sample (for example, a week of my messages in one channel, separated by blank lines). Never mix categories in one sample. Keep my wording, spelling, and punctuation exactly as written.

${fixed} Categories:
${categories}

Give each sample a short title and a stable source string I can recognize later: the document, thread, or PR URL; file:// plus the absolute path; or tool:id (for a combined sample, describe the range, e.g. slack:C0123:2026-10-01..2026-10-07).

## 3. Check for duplicates
Call find_samples with the sources of all candidates, in batches of up to 50. Mark any that already have a sample.

## 4. Review with me
Show a numbered table: title, category, source, characters, a one-line excerpt, and new or already in Tones. Then ask which to add and whether any categories should change. Do not call add_sample before I answer.

## 5. Add what I approve
Call add_sample once per approved sample with the final text, title, category (as register), and source. A result with duplicate true means Tones already had that text. When done, summarize what was added and skipped, and say that processing runs in the background (list_samples shows when samples are ready).`;
}
